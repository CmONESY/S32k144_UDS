/* ============================ LPI2C0 基础 ============================ */
/* LPI2C0 时钟已在工程 clock_config 里配好（8 MHz），无需再动 */
#define OLED_LPI2C_INSTANCE  0U   /* LPI2C0 */

static lpi2c_master_state_t oled_lpi2c_state;

static lpi2c_master_user_config_t oled_lpi2c_cfg =
{
    .slaveAddress  = OLED_I2C_ADDR,      /* 7 位地址 0x3C */
    .is10bitAddr   = false,
    .operatingMode = LPI2C_STANDARD_MODE,/* 100 kHz；想快点可改 LPI2C_FAST_MODE 并把 baudRate 改 400000 */
    .baudRate      = 100000UL,
    .transferType  = LPI2C_USING_INTERRUPTS,
    .dmaChannel    = 0U,
    .masterCallback = NULL,
    .callbackParam  = NULL
};

static void OLED_PinsInit(void)
{
    /* PTA2 = LPI2C0_SDA，PTA3 = LPI2C0_SCL，复用 ALT3 */
    PINS_DRV_SetMuxModeSel(PORTA, 2U, PORT_MUX_ALT3);
    PINS_DRV_SetMuxModeSel(PORTA, 3U, PORT_MUX_ALT3);
    PINS_DRV_SetPullSel(PORTA, 2U, PORT_INTERNAL_PULL_UP_ENABLED);
    PINS_DRV_SetPullSel(PORTA, 3U, PORT_INTERNAL_PULL_UP_ENABLED);
}

static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00U, cmd};      /* 控制字节 0x00：后面是命令 */
    (void)LPI2C_DRV_MasterSendDataBlocking(OLED_LPI2C_INSTANCE, buf, 2U, true, OSIF_WAIT_FOREVER);
}

static void OLED_WriteData(const uint8_t *data, uint32_t len)
{
    uint8_t buf[129];                    /* 1 个控制字节 + 最多 128 个数据字节 */
    uint32_t i;

    if (len > 128U)
    {
        len = 128U;
    }
    buf[0] = 0x40U;                      /* 控制字节 0x40：后面是数据 */
    for (i = 0U; i < len; i++)
    {
        buf[i + 1U] = data[i];
    }
    (void)LPI2C_DRV_MasterSendDataBlocking(OLED_LPI2C_INSTANCE, buf, len + 1U, true, OSIF_WAIT_FOREVER);
}

/* ============================ 显存 ============================ */
/* 128x64 = 8 页 x 128 列，每列一个字节，bit0 在屏幕最上方 */
static uint8_t OLED_GRAM[8][128];

void OLED_Clear(void)
{
    uint8_t y;
    uint8_t x;
    for (y = 0U; y < 8U; y++)
    {
        for (x = 0U; x < 128U; x++)
        {
            OLED_GRAM[y][x] = 0x00U;
        }
    }
}

void OLED_Update(void)
{
    uint8_t page;
    for (page = 0U; page < 8U; page++)
    {
        OLED_WriteCmd(0xB0U + page);     /* 页地址 */
        OLED_WriteCmd(0x00U);            /* 列地址低 4 位 */
        OLED_WriteCmd(0x10U);            /* 列地址高 4 位 */
        OLED_WriteData(&OLED_GRAM[page][0], 128U);
    }
}

