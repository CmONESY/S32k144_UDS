/* ============================ 显示接口 ============================ */
void OLED_ShowChar(uint8_t x, uint8_t y, char ch)
{
    uint8_t idx;
    uint8_t i;
    if ((ch < ' ') || (ch > '~'))
    {
        ch = ' ';
    }
    idx = (uint8_t)(ch - ' ');

    if (x > 122U)
    {
        x = 0U;
    }
    if (y > 7U)
    {
        y = 0U;
    }

    for (i = 0U; i < 6U; i++)
    {
        OLED_GRAM[y][x + i] = F6x8[idx][i];
    }
}

void OLED_ShowString(uint8_t x, uint8_t y, const char *str)
{
    while (*str != '\0')
    {
        if (x > 122U)
        {
            x = 0U;
            y++;
        }
        if (y > 7U)
        {
            break;
        }
        OLED_ShowChar(x, y, *str);
        str++;
        x += 6U;
    }
}

void OLED_ShowNum(uint8_t x, uint8_t y, int32_t num, uint8_t len)
{
    char buf[12];
    uint8_t i = 0U;
    bool neg = false;
    uint32_t val;

    if (num < 0)
    {
        neg = true;
        val = (uint32_t)(-num);
    }
    else
    {
        val = (uint32_t)num;
    }

    do
    {
        buf[i] = (char)('0' + (uint8_t)(val % 10U));
        val /= 10U;
        i++;
    } while (val != 0U);

    while (i < len)
    {
        buf[i] = '0';
        i++;
    }
    if (neg)
    {
        buf[i] = '-';
        i++;
    }

    while (i > 0U)
    {
        i--;
        OLED_ShowChar(x, y, buf[i]);
        x += 6U;
    }
}

/* ============================ 初始化 ============================ */
void OLED_Init(void)
{
    OLED_PinsInit();

    (void)LPI2C_DRV_MasterInit(OLED_LPI2C_INSTANCE, &oled_lpi2c_cfg, &oled_lpi2c_state);

    OLED_WriteCmd(0xAE);              /* 关显示 */
    OLED_WriteCmd(0xD5);              /* 时钟分频 */
    OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8);              /* 复用率 1/64 */
    OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3);              /* 显示偏移 */
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40);              /* 起始行 0 */
    OLED_WriteCmd(0x8D);              /* 电荷泵 */
    OLED_WriteCmd(0x14);
    OLED_WriteCmd(0x20);              /* 页寻址模式 */
    OLED_WriteCmd(0x02);
    OLED_WriteCmd(0xA1);              /* 段重映射：左右镜像方向 */
    OLED_WriteCmd(0xC8);              /* COM 扫描方向：上下镜像方向 */
    OLED_WriteCmd(0xDA);              /* COM 引脚配置 */
    OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81);              /* 对比度 */
    OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9);              /* 预充电周期 */
    OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB);              /* VCOMH 电压 */
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0xA4);              /* 输出跟随显存 */
    OLED_WriteCmd(0xA6);              /* 正常显示（反显用 0xA7） */
    OLED_WriteCmd(0xAF);              /* 开显示 */

    OLED_Clear();
    OLED_Update();
}
